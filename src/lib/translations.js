export const getTranslation = (langId) => {
  const primary = translations[langId] || translations.hi || translations.en;
  return new Proxy(primary, {
    get(target, prop) {
      if (typeof prop === "string") {
        if (prop in target && target[prop] !== undefined && target[prop] !== "") {
          return target[prop];
        }
        if (translations.hi && prop in translations.hi && translations.hi[prop] !== undefined && translations.hi[prop] !== "") {
          return translations.hi[prop];
        }
        if (translations.en && prop in translations.en && translations.en[prop] !== undefined && translations.en[prop] !== "") {
          return translations.en[prop];
        }
      }
      return target[prop];
    }
  });
};

